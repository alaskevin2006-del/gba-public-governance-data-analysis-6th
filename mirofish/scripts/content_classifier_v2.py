# 引用式否定的处理：把引号内的片段剔除后再检测"断言为真"标记。
# 例：「别光转"坠楼"那种吓人话了」中的"坠楼"是被引用的否定对象，不是断言。
_QUOTE_PAIRS = [("“", "”"), ("「", "」"), ("《", "》"), ("\"", "\""), ("'", "'")]


def strip_quoted(text):
    import re
    out = str(text)
    for l, r in _QUOTE_PAIRS:
        out = re.sub(f"{re.escape(l)}[^{re.escape(l + r)}]{{0,60}}{re.escape(r)}", "", out)
    return out


def classify(text, return_evidence=False):
    """返回 'debunk' / 'rumor' / 'neutral'。"""
    if not text:
        return ("neutral", {}) if return_evidence else "neutral"
    t = str(text)
    low = t.lower()
    t_unquoted = strip_quoted(t)          # 检测"断言为真"时忽略被引用的片段
    low_uq = t_unquoted.lower()

    ev = {
        "debunk_strong": [k for k in DEBUNK_STRONG if k.lower() in low],
        "debunk_weak": [k for k in DEBUNK_WEAK if k in t],
        "debunk_regret": [k for k in DEBUNK_REGRET if k in t],
        "rumor_claim": [k for k in RUMOR_CLAIM if k in t_unquoted],
        "rumor_mobilize": [k for k in RUMOR_MOBILIZE if k in t_unquoted],
    }

    label = "neutral"
    if ev["debunk_strong"] or ev["debunk_weak"] or ev["debunk_regret"]:
        # 命中任一辟谣信号即判辟谣侧：因为只要文本在劝阻/澄清，
        # 它就**不是**在放大谣言（这是本研究的因变量定义）。
        label = "debunk"
    elif ev["rumor_claim"] or ev["rumor_mobilize"]:
        label = "rumor"

    return (label, ev) if return_evidence else label


